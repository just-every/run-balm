import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
import {clinic,pastVisit,visitDate} from './clinic.mjs'

export async function denialResolverJourney(h,options={}){
 await h.finishSetup()
 const {service,practitioners:[therapist]}=await clinic(h)
 await h.cmd('staff.save',{id:therapist.id,name:'Priya Shah',email:therapist.email,role:'practitioner',credentials:'PT',active:true})
 await h.cmd('pay.npi.save',{staffId:therapist.id,npi:'1234567893'})
 await h.cmd('insurance.settings.save',{billingNpi:'1234567893',taxId:'123456789',address:'100 synthetic-balm-1',city:'Austin',state:'TX',postalCode:'78701',senderId:'BALMTEST',contactName:'Synthetic Clinic',contactPhone:'5125550100'})
 const payer=await h.cmd('insurance.payer.save',{name:'Aetna',payerId:'60054',receiverId:'AETNA',unitMethod:'cms',fees:[{code:'97110',cents:3500},{code:'97140',cents:2500}]})
 await h.cmd('insurance.enrollment.save',{payerId:payer.id,practitionerId:therapist.id,taxonomy:'225100000X',active:true})
 const patient=await h.cmd('client.save',{firstName:'Synthetic',lastName:'Balm',dateOfBirth:'1988-04-02'})
 const policy=await h.cmd('insurance.policy.save',{clientId:patient.id,payerId:payer.id,memberId:'synthetic-balm-1',relationship:'18',patientSex:'F',address:'100 synthetic-balm-1',city:'Austin',state:'TX',postalCode:'78701',startsOn:'2000-01-01',endsOn:'2099-12-31'})
 const visit=await pastVisit(h,patient.id,therapist,service.id),date=await visitDate(h,visit)
 await h.cmd('appointment.attend',{id:visit})
 const note=await h.cmd('note.write',{clientId:patient.id,appointmentId:visit,body:'Synthetic therapy: knee strength progressing with skilled treatment.',charges:[{code:'97110',minutes:23},{code:'97140',minutes:15}]},therapist.cookie)
 await h.cmd('note.sign',{id:note.id,revision:1,signature:'Priya Shah',attest:true},therapist.cookie)
 await h.cmd('pay.codes.save',{appointmentId:visit,icd10:'M25.561'})
 const invoice=await h.cmd('invoice.prepare',{appointmentId:visit});await h.cmd('invoice.approve',{id:invoice.id})
 const biller=await h.staff('AppealBiller','biller'),reception=await h.staff('AppealDesk','reception')
 const claim=await h.cmd('insurance.claim.prepare',{appointmentId:visit,policyId:policy.id},biller.cookie)
 assert.equal(claim.status,'ready')
 const batch=await h.cmd('insurance.batch.prepare',{claimIds:[claim.id]},biller.cookie)
 await h.send('/api/balm/insurance/837P/'+batch.id,undefined,biller.cookie)
 const referral=await h.cmd('case.open',{clientId:patient.id,policyId:policy.id,receivedOn:'2000-01-01',referringFirst:'Synthetic',referringLast:'Provider'})
 const view=async(cookie=biller.cookie)=>{const r=await h.send('/api/balm/cases',undefined,cookie);assert.equal(r.status,200,r.text);return r.value.cases.find(c=>c.referral.id===referral.id)}
 const fixture=async name=>(await readFile(new URL('./fixtures/insurance/'+name,import.meta.url),'utf8')).replaceAll('{{CLAIM}}',claim.id)
 await h.cmd('insurance.acknowledgment.import',{payerId:payer.id,x12:(await fixture('277CA.x12')).replace('A2:20','A3:21:85')},biller.cookie)
 const rejected=await view(),fix=rejected.steps.find(s=>s.kind==='denial.fix')
 assert.match(fix.why,/Required information is missing or invalid for the billing provider/)
 assert.ok(fix.citations.some(c=>c.kind==='acknowledgment'&&c.label==='277CA A3:21:85'))
 assert.ok(!fix.citations.some(c=>c.kind==='era'),'a 277CA rejection never invents an ERA')
 assert.equal(rejected.denials[0].state,'awaiting_payment')
 await options.rejected?.({h,patient,biller,referral,claim})
 await h.cmd('insurance.remittance.import',{payerId:payer.id,x12:await fixture('835-denied.x12')},biller.cookie)
 const auth=await h.cmd('insurance.authorization.save',{policyId:policy.id,number:'synthetic-balm-2',startsOn:'2000-01-01',endsOn:'2099-12-31',visits:12},biller.cookie)
 const preparation={caseId:referral.id,claimId:claim.id}
 for(const cookie of [reception.cookie,therapist.cookie])await h.cmd('case.appeal.prepare',preparation,cookie,403)
 const beforeMail=h.mail.length
 const release=await h.cmd('case.appeal.prepare',preparation,biller.cookie)
 let step=(await view()).steps.find(s=>s.kind==='denial.appeal')
 assert.ok(step.blocked)
 const approve=()=>({caseId:referral.id,key:step.key,digest:step.digest})
 await h.cmd('case.approve',approve(),biller.cookie,409)
 const pdfPath='/api/balm/note-releases/'+release.id+'.pdf'
 assert.equal((await h.send(pdfPath,undefined,biller.cookie)).status,403)
 assert.equal((await h.send(pdfPath,undefined,h.owner)).status,200)
 await h.cmd('note_release.approve',{id:release.id,sha256:release.sha256,attest:true})
 step=(await view()).steps.find(s=>s.kind==='denial.appeal')
 assert.equal(step.blocked,undefined)
 assert.match(step.appeal.letter,/Required authorization or advance notification was not supplied/)
 assert.match(step.appeal.letter,/recorded authorization synthetic-balm-2/)
 assert.deepEqual(new Set(step.citations.map(c=>c.kind)),new Set(['claim','era','note','authorization']))
 assert.ok(step.citations.some(c=>c.href.endsWith('#note-'+note.id)))
 assert.ok(step.citations.some(c=>c.href.endsWith('#authorization-'+auth.id)))
 await h.cmd('case.approve',approve(),biller.cookie,409)
 const pdf=await h.send(pdfPath,undefined,biller.cookie)
 assert.equal(pdf.status,200);assert.match(pdf.text,/knee strength progressing/)
 for(const cookie of [reception.cookie,therapist.cookie])await h.cmd('case.approve',approve(),cookie,403)
 await h.cmd('case.approve',{...approve(),digest:'stale'},biller.cookie,409)
 await options.prepared?.({h,patient,biller,referral,claim,step,release})
 const approvals=await Promise.all([1,2].map(()=>h.send('/api/balm/command',{name:'case.approve',input:approve()},biller.cookie)))
 assert.deepEqual(approvals.map(r=>r.status).sort(),[200,409],'concurrent billing approvals record one packet')
 const approved=await view(),history=approved.history.filter(s=>s.kind==='denial.appeal')
 assert.equal(history.length,1);assert.equal(history[0].approved_by,'appealbiller@clinic.example');assert.equal(history[0].approved_role,'biller')
 assert.equal(history[0].result.status,'approved_not_sent');assert.equal(history[0].result.releaseDigest,release.sha256)
 assert.equal(history[0].result.letter,step.appeal.letter)
 assert.equal(approved.denials[0].state,'awaiting_payment','approval never resolves a denial')
 assert.equal(h.mail.length,beforeMail,'appeal approval sends nothing')
 await options.approved?.({h,patient,biller,referral,claim})
 await h.cmd('insurance.remittance.import',{payerId:payer.id,x12:await fixture('835-paid.x12')},biller.cookie)
 await h.cmd('insurance.remittance.import',{payerId:payer.id,x12:await fixture('835-paid.x12')},biller.cookie)
 const originals=await h.db.prepare('SELECT paid_cents,detail FROM bm_cob_adjudications WHERE claim_id=? ORDER BY rowid').bind(claim.id).all()
 assert.deepEqual(originals.results.map(r=>r.paid_cents),[0,6000],'both original denial and appeal payment survive')
 const file=(await h.send('/api/balm/clients/'+patient.id,undefined,biller.cookie)).value
 assert.equal(file.billing.ledger.paymentsCents,6000);assert.equal(file.billing.ledger.patientBalanceCents,1500)
 const paid=await view()
 assert.deepEqual(paid.denials,[{claimId:claim.id,state:'resolved',paidCents:6000}])
 assert.equal(paid.history.filter(s=>s.kind==='denial.appeal').length,1)
 await options.paid?.({h,patient,biller,referral,claim})
 await h.cmd('note_release.revoke',{id:release.id})
 assert.equal((await h.send(pdfPath,undefined,biller.cookie)).status,403)
 const audit=await h.db.prepare("SELECT action FROM bm_audit WHERE subject_id=?").bind(release.id).all()
 for(const action of ['note_release.prepared','note_release.reviewed','note_release.approved','note_release.downloaded','note_release.revoked'])assert.ok(audit.results.some(r=>r.action===action),action)
}
