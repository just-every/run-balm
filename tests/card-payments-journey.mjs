/** Full money flow through patient and staff HTTP doors; only provider edges vary. */
export async function cardPaymentsJourney({ h, stripe, service, priya, reception, client }, hooks = {}) {
  await h.cmd('service.save',{id:service.id,name:'Therapy follow-up',durationMinutes:15,priceCents:9500})
  const at = new Date(Math.floor(Date.now()/900000)*900000+900000), local = new Date(at.getTime()+10*3600000).toISOString()
  const booked = await h.cmd('appointment.book', {clientId:client.id,practitionerId:priya.id,serviceId:service.id,date:local.slice(0,10),time:local.slice(11,16)}, reception.cookie)
  const intakePath = '/intake/'+booked.token
  const page = await h.send(intakePath)
  assert.equal(page.status,200);assert.match(page.text,/Save a payment card/)
  assert.equal((await h.form(intakePath+'?do=card',{})).status,400)
  const complete = hooks.checkout ?? (async (started, source) => {
    assert.equal(started.status,303,started.text)
    const sessionId=started.location.split('/').at(-1)
    stripe.complete(sessionId)
    const session=stripe.sessions.get(sessionId)
    return h.send(source+'?setup='+session.id,undefined,source.startsWith('/portal')?cookie:'')
  })
  await hooks.screen?.('intake',intakePath,'#payment-card', '')
  const saved = await complete(hooks.startCard ? await hooks.startCard(intakePath, '') : await h.form(intakePath+'?do=card',{consent:'on'}),intakePath)
  assert.equal(saved.status,200,saved.text)
  const setup=await h.db.prepare("SELECT * FROM bm_card_setups WHERE client_id=? AND source='intake'").bind(client.id).first()
  assert.equal(setup.status,'saved');assert.match(setup.consent_text,/I authorize/);assert.equal(setup.consented_by,'intake link holder')
  await hooks.cardSaved?.('intake',setup)
  await hooks.screen?.('intake-saved',intakePath,'#payment-card','')
  await h.cmd('pay.copay.save',{clientId:client.id,copay:'30.00'},reception.cookie)
  const cookie=await portalLogin(h,'ava@client.example')
  assert.equal((await h.form('/portal/action',{name:'payment.card'},cookie)).status,400)
  await hooks.screen?.('portal-card','/portal/home','#payment-card form',cookie)
  const replaced=await complete(hooks.startCard ? await hooks.startCard('/portal/home', cookie) : await h.form('/portal/action',{name:'payment.card',consent:'on',clientId:'foreign'},cookie),'/portal/home')
  assert.equal(replaced.status,200,replaced.text)
  const portalSetup=await h.db.prepare("SELECT * FROM bm_card_setups WHERE client_id=? AND source='portal'").bind(client.id).first()
  assert.equal(portalSetup.status,'saved');assert.equal(portalSetup.consented_by,'patient-portal')
  await hooks.cardSaved?.('portal',portalSetup)
  await hooks.screen?.('portal-saved','/portal/home','#payment-card',cookie)
  const card=await h.db.prepare('SELECT * FROM bm_cards WHERE client_id=? AND removed_at IS NULL').bind(client.id).first()
  assert.equal(card.id,portalSetup.card_id);assert.ok(card.consent_sha256);assert.ok(card.setup_intent)
  if(hooks.checkin)await hooks.checkin(booked.appointmentId,local.slice(0,10),reception.cookie)
  else await h.cmd('pay.checkin',{appointmentId:booked.appointmentId,charge:true},reception.cookie)
  const payment=await h.db.prepare("SELECT * FROM bm_card_payments WHERE appointment_id=? AND status='succeeded'").bind(booked.appointmentId).first()
  assert.equal(payment.amount_cents,3000);assert.ok(payment.payment_intent)
  await h.cmd('appointment.attend',{id:booked.appointmentId},priya.cookie)
  await h.cmd('pay.npi.save',{staffId:priya.id,npi:'1234567893'})
  await h.cmd('settings.save',{clinicName:'Riverside Physio',timeZone:'Australia/Brisbane',practiceNpi:'1234567893',taxId:'12-3456789',address:'1 River St'})
  await h.cmd('pay.codes.save',{appointmentId:booked.appointmentId,cpt:'97110 GP x3',icd10:'M25.561'},priya.cookie)
  const invoice=await h.cmd('invoice.prepare',{appointmentId:booked.appointmentId},reception.cookie)
  await h.cmd('invoice.approve',{id:invoice.id},reception.cookie)
  const original=await h.send('/portal/receipts/'+payment.id+'.pdf',undefined,cookie)
  assert.equal(original.status,200)
  const file=async()=> (await h.send('/api/balm/clients/'+client.id,undefined,h.owner)).value
  assert.equal((await file()).billing.ledger.patientBalanceCents,6500)
  const prepared=await h.cmd('pay.refund.prepare',{clientId:client.id,paymentId:payment.id,amount:'30.00',reason:'Synthetic duplicate copay'},reception.cookie)
  assert.equal(prepared.status,'prepared');assert.equal((await file()).billing.ledger.patientBalanceCents,6500)
  await h.cmd('pay.refund.approve',{id:prepared.id,sha256:prepared.sha256,attest:true},reception.cookie,403)
  await h.cmd('pay.refund.approve',{id:prepared.id,sha256:'changed',attest:true},h.owner,409)
  await hooks.screen?.('refund-prepare','/app/clients/'+client.id,'form[action*="pay.refund.prepare"]',reception.cookie)
  await hooks.screen?.('refund-approval','/app/clients/'+client.id,'form[action*="pay.refund.approve"]',h.owner)
  const approved=await h.cmd('pay.refund.approve',{id:prepared.id,sha256:prepared.sha256,attest:true})
  assert.equal(approved.status,'confirmed',JSON.stringify(approved));assert.ok(approved.provider_refund_id);assert.equal(approved.approved_by,'owner@clinic.example')
  const replay=await h.cmd('pay.refund.approve',{id:prepared.id,sha256:prepared.sha256,attest:true})
  assert.equal(replay.provider_refund_id,approved.provider_refund_id)
  const after=await file()
  assert.equal(after.billing.ledger.patientBalanceCents,9500);assert.equal(after.billing.ledger.creditCents,0)
  assert.equal(after.invoices[0].paid_cents,0)
  assert.equal(after.billing.ledger.lines.filter(x=>x.kind==='refund').length,1)
  assert.equal((await h.send('/portal/receipts/'+payment.id+'.pdf',undefined,cookie)).text,original.text)
  assert.equal((await h.send('/portal/refund-receipts/'+approved.id+'.pdf',undefined,cookie)).status,200)
  assert.equal((await h.send('/portal/superbills/'+invoice.id+'.pdf',undefined,cookie)).status,200)
  await hooks.screen?.('refund-ledger','/app/clients/'+client.id,'#billing',h.owner)
  await hooks.screen?.('refund-portal','/portal/home','#statements',cookie)
  const privateLink=await h.cmd('pay.link.create',{clientId:client.id,purpose:'balance',delivery:'shown'},reception.cookie)
  const payPath=new URL(privateLink.url).pathname
  assert.equal((await h.send(payPath+'/refund-receipts/'+approved.id+'.pdf')).status,200)
  await hooks.screen?.('refund-link',payPath,'.grid','')
  const foreign=await h.cmd('client.save',{firstName:'Other',lastName:'Synthetic',email:'other@patient.example'})
  const foreignCookie=await portalLogin(h,'other@patient.example')
  assert.equal((await h.send('/portal/refund-receipts/'+approved.id+'.pdf',undefined,foreignCookie)).status,404)
  const reportQuery='from='+new Date(at.getTime()-86400000+10*3600000).toISOString().slice(0,10)+'&to='+new Date(at.getTime()+86400000+10*3600000).toISOString().slice(0,10)
  const reportResponse=await h.send('/api/balm/reports/financial?'+reportQuery,undefined,h.owner)
  assert.equal(reportResponse.status,200,reportResponse.text)
  const report=reportResponse.value
  assert.equal(report.deposits.total.receivedCents,0);assert.equal(report.deposits.total.refundedCents,3000)
  assert.equal(report.summary.arCents,9500)
  await hooks.screen?.('refund-report','/app/reports?'+reportQuery,'#report-deposits',h.owner)
  await hooks.refunded?.({h,client,cookie,payment,approved,setup,portalSetup,invoice,foreign})
  // A distinct visit uses Stripe's server-driven reader rather than a saved card.
  const secondDate=new Date(at.getTime()+3600000),secondLocal=new Date(secondDate.getTime()+10*3600000).toISOString()
  const second=await h.cmd('appointment.book',{clientId:client.id,practitionerId:priya.id,serviceId:service.id,date:secondLocal.slice(0,10),time:secondLocal.slice(11,16)},reception.cookie)
  await h.cmd('pay.terminal.configure',{locationId:hooks.locationId ?? 'tml_syntheticbalm1',simulated:true})
  await hooks.screen?.('terminal-settings','/app/clinic','form[action*="pay.terminal.configure"]',h.owner)
  await hooks.screen?.('terminal-register','/app/clinic','form:has(input[name=registrationCode])',h.owner)
  await hooks.screen?.('terminal-simulator','/app/clinic','form:has(input[name=simulated])',h.owner)
  const uiPayment=hooks.collect?await hooks.collect(second.appointmentId,secondLocal.slice(0,10),reception.cookie):null
  const paymentId=uiPayment?.id ?? randomUUID()
  const waiting=uiPayment ?? await h.cmd('pay.terminal.collect',{appointmentId:second.appointmentId,paymentId,amount:'30.00'},reception.cookie)
  assert.equal(waiting.status,'processing')
  const repeat=await h.cmd('pay.terminal.collect',{appointmentId:second.appointmentId,paymentId,amount:'30.00'},reception.cookie)
  assert.equal(repeat.payment_intent,waiting.payment_intent)
  await h.cmd('pay.copay.charge',{appointmentId:second.appointmentId},reception.cookie,409)
  const day=secondLocal.slice(0,10)
  await hooks.screen?.('terminal-pending','/app?date='+day,'form[action*="pay.terminal.simulate"]',reception.cookie)
  let paid=await h.cmd('pay.terminal.simulate',{paymentId},reception.cookie)
  for(let i=0;i<8&&paid.status!=='succeeded';i++){await new Promise(r=>setTimeout(r,700));paid=await h.cmd('pay.terminal.sync',{paymentId},reception.cookie)}
  assert.equal(paid.status,'succeeded',JSON.stringify(paid));assert.equal(paid.amount_cents,3000)
  await h.cmd('pay.terminal.sync',{paymentId},reception.cookie)
  assert.equal((await h.send('/portal/receipts/'+paymentId+'.pdf',undefined,cookie)).status,200)
  assert.equal((await file()).billing.ledger.patientBalanceCents,6500)
  await hooks.screen?.('terminal-paid','/app?date='+day,'a[href="/api/balm/receipts/'+paymentId+'.pdf"]',reception.cookie)
  await hooks.screen?.('terminal-portal','/portal/home','#statements',cookie)
  let auditFile=await file();const audit=[...auditFile.audit]
  while(auditFile.auditPage.older){auditFile=(await h.send('/api/balm/clients/'+client.id+'?auditBefore='+auditFile.auditPage.older,undefined,h.owner)).value;audit.push(...auditFile.audit)}
  for(const action of ['card.entry_authorized','card.saved','payment.refund_approved','payment.refund_confirmed','payment.terminal_started'])assert.ok(audit.some(x=>x.action===action),action)
  if(stripe)await checkInResponsibilityJourney({h,stripe,service,priya,reception},hooks)
  return {client,setup,portalSetup,payment,refund:approved,terminal:paid}
}

