import assert from 'node:assert/strict'
import {clinic,slots} from './clinic.mjs'
import {portalLogin} from './portal-billing.mjs'

export async function bookingPrepaymentJourney(h,stripe,hooks={}){
 await h.finishSetup()
 const {service,practitioners:[priya]}=await clinic(h)
 const reception=await h.staff('PrepaymentDesk','reception')
 await h.cmd('pay.stripe.connect',{secretKey:'synthetic-balm-1'})
 await h.cmd('service.save',{id:service.id,prepayMode:'deposit',depositCents:3000},reception.cookie,403)
 await h.cmd('service.save',{id:service.id,prepayMode:'deposit',depositCents:10000},h.owner,400)
 await h.cmd('service.save',{id:service.id,prepayMode:'deposit',depositCents:3000})
 await hooks.screen?.('booking-settings','/app/clinic','form:has([name=prepayMode])',h.owner)
 const starts=await slots(h,service.id,priya.id)
 const selected=async()=> (await h.state()).services.find(s=>s.id===service.id)
 const fields=async(start,extra={})=>({serviceId:service.id,practitionerId:priya.id,start,firstName:'Ava',lastName:'Ng',dateOfBirth:'1992-06-15',email:'ava@client.example',privacy:'on',coverageChoice:'self_pay',deliveryMethod:'portal',confirmPayment:'on',confirmedAmountCents:3000,serviceVersion:(await selected()).version,...extra})
 const booking=await fields(starts[0])
 const pagePath=`/book?serviceId=${service.id}&practitionerId=${priya.id}&start=${encodeURIComponent(starts[0])}`
 await hooks.screen?.('booking-amount',pagePath,'#details','')
 assert.equal((await h.form('/book',{...booking,confirmPayment:''})).status,400)
 await h.cmd('service.save',{id:service.id,depositCents:3500})
 assert.equal((await h.form('/book',booking)).status,409,'stale amount is refused before a reservation or provider write')
 assert.equal(stripe.sessions.size,0)
 await h.cmd('service.save',{id:service.id,depositCents:3000})
 const reserved=await h.form('/book',await fields(starts[0]))
 assert.equal(reserved.status,303,reserved.text);assert.match(reserved.location,/^\/book\/payment\//)
 assert.equal((await h.state()).appointments.length,0,'unpaid reservation is not a visit')
 const reservation=await h.db.prepare('SELECT * FROM bm_booking_payments').first()
 assert.notEqual((await h.db.prepare('SELECT token_hash FROM bm_booking_payment_tokens WHERE id=?').bind(reservation.id).first()).token_hash,reserved.location.split('/').at(-1))
 const outcomes=await Promise.all([h.form('/book',await fields(starts[0],{firstName:'Other',email:'other@patient.example'})),h.form('/book',await fields(starts[0],{firstName:'Third',email:'third@patient.example'}))])
 assert.deepEqual(outcomes.map(r=>r.status),[409,409]);assert.equal(stripe.sessions.size,0)
 const client=(await h.state()).clients.find(c=>c.id===reservation.client_id)
 await h.cmd('appointment.book',{clientId:client.id,practitionerId:priya.id,serviceId:service.id,date:new Date(Date.parse(starts[0])+10*3600000).toISOString().slice(0,10),time:new Date(Date.parse(starts[0])+10*3600000).toISOString().slice(11,16)},h.owner,409)
 await hooks.screen?.('booking-checkout',reserved.location,'main','')
 const cookie=await portalLogin(h,'ava@client.example')
 const foreign=await h.cmd('client.save',{firstName:'Foreign',lastName:'Patient',email:'foreign@patient.example'})
 const foreignCookie=await portalLogin(h,'foreign@patient.example')
 const beforeShared=await h.state()
 const sharedEmail=(await h.send('/api/balm/clients/'+foreign.id,undefined,h.owner)).value.client.email
 const shared=await h.form('/book',await fields(starts[4],{firstName:'Synthetic',lastName:'Shared',email:sharedEmail}))
 assert.equal(shared.status,409,'a different patient sharing an existing sign-in must contact the clinic before money is requested')
 assert.equal((await h.state()).clients.length,beforeShared.clients.length)
 assert.equal((await h.db.prepare('SELECT COUNT(*) AS n FROM bm_booking_payments').first()).n,1)
 assert.equal(stripe.sessions.size,0,'ambiguous receipt access creates neither a reservation nor Checkout')
 assert.equal((await h.form('/portal/action',{name:'booking.payment',id:reservation.id},foreignCookie)).status,404)
 const started=await h.form('/portal/action',{name:'booking.payment',id:reservation.id},cookie)
 assert.equal(started.status,303,started.text)
 const sessionId=started.location.split('/').at(-1)
 const repeated=await h.form(reserved.location,{})
 assert.equal(repeated.location,started.location);assert.equal(stripe.sessions.size,1)
 assert.equal((await h.send(reserved.location+'?paid=made-up')).status,200)
 assert.equal((await h.state()).appointments.length,0)
 await h.cmd('service.save',{id:service.id,priceCents:12000,depositCents:4000})
 stripe.complete(sessionId)
 await Promise.all([h.send(reserved.location),h.send(reserved.location)])
 const paid=await h.db.prepare('SELECT * FROM bm_card_payments WHERE id=?').bind(reservation.payment_id).first()
 assert.equal(paid.status,'succeeded');assert.equal(paid.amount_cents,3000);assert.equal(paid.appointment_id,reservation.appointment_id)
 assert.equal((await h.state()).appointments.length,1)
 const visit=(await h.state()).appointments[0]
 assert.equal((await h.db.prepare('SELECT coverage_choice FROM bm_appointments WHERE id=?').bind(visit.id).first()).coverage_choice,'self_pay')
 const receipt=await h.send('/portal/receipts/'+paid.id+'.pdf',undefined,cookie)
 assert.equal(receipt.status,200);assert.match(receipt.text,/\$30\.00/);assert.match(receipt.text,/Online booking deposit/)
 assert.equal((await h.send('/portal/receipts/'+paid.id+'.pdf',undefined,foreignCookie)).status,404)
 const portal=await h.send('/portal/home',undefined,cookie)
 assert.match(portal.text,/Appointment confirmed/);assert.ok(portal.text.includes('/portal/receipts/'+paid.id+'.pdf'))
 await hooks.screen?.('booking-portal','/portal/home','#statements',cookie)
 await h.cmd('settings.save',{clinicName:'Changed clinic',timeZone:'Australia/Brisbane'})
 assert.equal((await h.send('/portal/receipts/'+paid.id+'.pdf',undefined,cookie)).text,receipt.text)
 const file=(await h.send('/api/balm/clients/'+client.id,undefined,h.owner)).value
 assert.equal(file.billing.payments.find(p=>p.id===paid.id).appointment_id,visit.id)
 assert.match((await h.send('/app/clients/'+client.id,undefined,h.owner)).text,/Booking deposit \$30\.00 paid/)
 await hooks.screen?.('booking-visit','/app/clients/'+client.id,'#codes-'+visit.id,h.owner)
 assert.equal(file.billing.ledger.paymentsCents,3000);assert.equal(file.billing.ledger.creditCents,3000)
 const careTime=new Date(Date.now()-3600000+10*3600000).toISOString()
 await h.cmd('appointment.move',{id:visit.id,date:careTime.slice(0,10),time:careTime.slice(11,16)})
 await h.cmd('appointment.attend',{id:visit.id},priya.cookie)
 const invoice=await h.cmd('invoice.prepare',{appointmentId:visit.id})
 await h.cmd('invoice.approve',{id:invoice.id})
 const billed=(await h.send('/api/balm/clients/'+client.id,undefined,h.owner)).value
 assert.equal(billed.invoices[0].amount_cents,9500);assert.equal(billed.invoices[0].paid_cents,3000)
 assert.equal(billed.billing.ledger.balanceCents,6500)
 assert.equal((await h.send('/portal/receipts/'+paid.id+'.pdf',undefined,cookie)).text,receipt.text)
 // Full prepayment reuses the same public flow, with current terms and exact cents.
 await h.cmd('service.save',{id:service.id,prepayMode:'full'})
 const full=await h.form('/book',await fields(starts[8],{confirmedAmountCents:12000}))
 assert.equal(full.status,303,full.text)
 const fullStart=await h.form(full.location,{})
 stripe.complete(fullStart.location.split('/').at(-1))
 await h.send(full.location)
 const fullRow=await h.db.prepare('SELECT * FROM bm_booking_payments WHERE amount_cents=12000').first()
 assert.equal(fullRow.state,'booked')
 const fullPayment=await h.db.prepare('SELECT * FROM bm_card_payments WHERE id=?').bind(fullRow.payment_id).first()
 assert.equal(fullPayment.amount_cents,12000);assert.equal(fullPayment.appointment_id,fullRow.appointment_id)
 assert.match((await h.send('/portal/receipts/'+fullPayment.id+'.pdf',undefined,cookie)).text,/\$120\.00/)
 return {client,service,priya,reservation,paid,receipt,cookie,foreign,foreignCookie,fullRow}
}
